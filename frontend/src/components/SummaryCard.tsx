import { useState } from 'react'

import { useGenerateSummary, useSummary, type Summary, type SummaryItem } from '../lib/queries'

/** Human labels for the stats computed in code (backend ai/summary.py). */
const STAT_LABELS: Record<string, [string, (v: unknown) => string]> = {
  time_in_range_pct: ['Time in range (70–180)', (v) => `${String(v)}%`],
  mean_mg_dl: ['Average', (v) => `${String(v)} mg/dL`],
  low_pct: ['Low (54–69)', (v) => `${String(v)}%`],
  very_low_pct: ['Very low (<54)', (v) => `${String(v)}%`],
  high_pct: ['High (181–250)', (v) => `${String(v)}%`],
  very_high_pct: ['Very high (>250)', (v) => `${String(v)}%`],
  cv_pct: ['Variability (CV)', (v) => (v === null ? '—' : `${String(v)}%`)],
  hours_with_lows: ['Hours with a low', (v) => String(v)],
  readings_count: ['Readings', (v) => Number(v).toLocaleString()],
  child_chat_messages: ['Messages to Scout', (v) => String(v)],
  companion_safety_escalations: ['Chat escalations', (v) => String(v)],
  mood_checkins: ['Mood check-ins', (v) => String(v)],
  mood_avg: ['Average mood', (v) => (v === null ? '—' : `${String(v)} of 5`)],
  low_mood_checkins: ['Low-mood check-ins (1–2)', (v) => String(v)],
  latest_mood: ['Latest mood', (v) => (v === null ? '—' : `${String(v)} of 5`)],
}

function statText(stats: Record<string, unknown>, key: string): string {
  const def = STAT_LABELS[key]
  if (!def) return key.replaceAll('_', ' ')
  return `${def[0]}: ${def[1](stats[key])}`
}

function Items({ title, items, stats }: { title: string; items: SummaryItem[]; stats: Record<string, unknown> }) {
  if (items.length === 0) return null
  return (
    <>
      <h3>{title}</h3>
      <ul className="summary-items">
        {items.map((it, i) => (
          <li key={i}>
            <p>{it.text}</p>
            <p className="summary-cites">
              Based on{' '}
              {it.stat_keys.map((k) => (
                <a key={k} className="cite" href={`#stat-${k}`}>
                  {statText(stats, k)}
                </a>
              ))}
              <span className="confidence">· {it.confidence} confidence</span>
            </p>
          </li>
        ))}
      </ul>
    </>
  )
}

function StatsTable({ stats }: { stats: Record<string, unknown> }) {
  return (
    <table className="status-table stats-table">
      <caption className="visually-hidden">Statistics computed from the last 7 days of readings</caption>
      <tbody>
        {Object.keys(STAT_LABELS)
          .filter((k) => k in stats)
          .map((k) => (
            <tr key={k} id={`stat-${k}`}>
              <th scope="row">{STAT_LABELS[k]?.[0]}</th>
              <td className="num">{STAT_LABELS[k]?.[1](stats[k])}</td>
            </tr>
          ))}
      </tbody>
    </table>
  )
}

const STATUS_NOTE: Record<Exclude<Summary['status'], 'ok'>, string> = {
  rejected: 'The AI draft was rejected by our safety checks, so only the computed numbers are shown.',
  error: 'The AI summary could not be generated right now. The computed numbers are below.',
  disabled: 'AI summaries are off (no NVIDIA API key). The computed numbers are below.',
}

export function SummaryCard() {
  const { data } = useSummary()
  const generate = useGenerateSummary()
  const [showStats, setShowStats] = useState(true)

  return (
    <section className="card" aria-labelledby="summary-h">
      <div className="card-head">
        <h2 id="summary-h">Weekly summary</h2>
        <button className="btn" onClick={() => generate.mutate()} disabled={generate.isPending}>
          {generate.isPending ? 'Writing…' : data ? 'Regenerate' : 'Generate summary'}
        </button>
      </div>

      {!data ? (
        <p className="empty">No summary yet. Generate one from the last 7 days.</p>
      ) : (
        <>
          {data.content && data.status === 'ok' ? (
            <div className="summary-ai">
              <p className="ai-badge">
                <span aria-hidden="true">✦</span> AI-generated by {data.model ?? 'model'} · numbers computed in code
              </p>
              <p className="summary-headline">{data.content.headline}</p>
              <Items title="Observations" items={data.content.observations} stats={data.stats} />
              <Items title="Patterns" items={data.content.patterns} stats={data.stats} />
              <Items title="Wellbeing" items={data.content.wellbeing_notes} stats={data.stats} />
              {data.content.discuss_with_care_team.length > 0 ? (
                <>
                  <h3>To discuss with the care team</h3>
                  <ul className="summary-discuss">
                    {data.content.discuss_with_care_team.map((d, i) => (
                      <li key={i}>{d}</li>
                    ))}
                  </ul>
                </>
              ) : null}
            </div>
          ) : (
            <p className="section-note">{STATUS_NOTE[data.status as Exclude<Summary['status'], 'ok'>]}</p>
          )}
          <button className="link-btn" onClick={() => setShowStats((s) => !s)} aria-expanded={showStats}>
            {showStats ? 'Hide' : 'Show'} the numbers
          </button>
          {showStats ? <StatsTable stats={data.stats} /> : null}
        </>
      )}
      {generate.isError ? <p className="form-error">Couldn’t generate a summary.</p> : null}
    </section>
  )
}
